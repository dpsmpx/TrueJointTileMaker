// Язык интерфейса (план «Интерфейс», D4, UX-52). Строки интерфейса пишутся
// в коде по-русски, как у оригинала, а перевод лежит таблицей рядом с
// программой: Resources/Lang/en.txt, строка — «русский<TAB>английский».
// Переводит шрифт, когда рисует и меряет строку: так подписи переводятся
// все разом, и раскладка экранов меряет уже переведённый текст.
//
// В таблице бывают:
//   - строка целиком: «Сохранить как<TAB>Save as»;
//   - шаблон, где {} — любое непустое: «строки {}–{} из {}<TAB>lines {}–{}
//     of {}»; подставленное переводится тоже, если оно есть в таблице;
//   - кусок, «~» в начале: «~Пробел<TAB>Space» — заменяется внутри строки,
//     если целиком и шаблоном она не нашлась (имена клавиш в сочетаниях).
// «\n» в обеих частях — перевод строки.
#pragma once

#include <string>
#include <vector>

namespace tjtm::i18n {

/// Язык: «ru» — строки как в коде, «en» — по таблице.
void setLanguage(const std::string& lang);
const std::string& language();

/// Загружает таблицу перевода; прежняя заменяется. Возвращает число строк,
/// пустую таблицу — если файла нет.
int loadCatalog(const std::string& path);
/// То же из текста (тесты). Возвращает число строк.
int loadCatalogText(const std::string& text);
/// Строки таблицы, которые не разобрались: без табуляции, с разным
/// числом {} слева и справа. Для тестов.
std::vector<std::string> catalogProblems(const std::string& text);

/// Строка на текущем языке: перевод или она сама. Ссылка живёт до
/// следующего вызова.
const std::string& text(const std::string& s);
/// То же копией.
std::string tr(const std::string& s);
/// Есть ли у строки перевод в таблице (целиком или шаблоном).
bool has(const std::string& s);

/// Учёт пропусков: строки с кириллицей, нарисованные не на русском без
/// перевода или с кириллицей после перевода. Для прогонов сценариев по-
/// английски (TJTM_I18N_MISSES): так видно, что не переведено на редких
/// экранах, без разглядывания снимков.
void trackMisses(bool on);
std::vector<std::string> misses();

/// Внутри области шрифт рисует строки как есть: набираемое поле, имена
/// файлов и слоёв — это данные человека, а не подписи.
class Raw {
public:
    Raw();
    ~Raw();
    Raw(const Raw&) = delete;
    Raw& operator=(const Raw&) = delete;
};

}  // namespace tjtm::i18n
