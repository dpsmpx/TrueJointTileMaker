Grid<Color> gridFromBgra(const std::vector<std::uint8_t>& raw, int size) {
    Grid<Color> g(size, size);
    for (std::size_t i = 0; i < g.d.size() && i * 4 + 3 < raw.size(); ++i) {
        g.d[i] = Color(raw[i * 4 + 3], raw[i * 4 + 2], raw[i * 4 + 1], raw[i * 4]);
    }
    return g;
}

